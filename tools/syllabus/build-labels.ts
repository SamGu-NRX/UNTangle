const entries = LABELS.map(([hash, attendance, examCount, grading]) => {
  const meta = byKey.get(hash);
  if (!meta) throw new Error(`no manifest row for ${hash}`);
  const text = readFileSync(path.join(root, "tools/syllabus/.cache/text", `${hash}.txt`), "utf8");
  const docQuote = text.replace(/\s+/g, " ").slice(0, 150);
  return {
    id: hash.slice(0, 8),
    course: meta.courseCode ?? "",
    section: meta.section ?? "",
    faculty: meta.faculty ?? null,
    profileUrl: meta.profileUrl ?? "",
    syllabusUrl: meta.syllabusUrl,
    docQuote,
    textSha256: createHash("sha256").update(text, "utf8").digest("hex"),
    attendance: attendance[1] !== undefined ? { present: attendance[0], excerpt: attendance[1] } : { present: attendance[0] },
    examCount:
      examCount[1] !== undefined
        ? { present: examCount[0], count: examCount[1], excerpt: examCount[2] }
        : { present: examCount[0] },
    gradingWeights: grading[1] !== undefined ? { present: grading[0], components: grading[1] } : { present: grading[0] },
  };
});

const out = { labeledBy: "hand-labeled from tools/syllabus/.cache/text before scoring", entries };
const dst = path.join(root, "docs/research/syllabus/labels.json");
mkdirSync(path.dirname(dst), { recursive: true });
writeFileSync(dst, JSON.stringify(out, null, 2) + "\n");
console.log(`labels: ${entries.length} entries -> ${dst}`);
